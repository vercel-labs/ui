import { Toolbar, ToolbarButton, ToolbarLink, ToolbarSeparator } from "@ui-sdk/solid/toolbar"
import { createSignal } from "solid-js"

function Example() {
  const [page, setPage] = createSignal("conversation")
  const follow = (event: MouseEvent & { currentTarget: HTMLAnchorElement }) => {
    if (event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) {
      return
    }
    event.preventDefault()
    setPage(event.currentTarget.hash.slice(1))
  }
  return (
    <div data-slot="stack">
      <Toolbar aria-label="Pull request">
        <ToolbarButton data-variant="secondary" aria-label="Approve">
          <svg
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="2"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
          >
            <path d="M20 6 9 17l-5-5" />
          </svg>
        </ToolbarButton>
        <ToolbarButton data-variant="secondary" aria-label="Comment">
          <svg
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="2"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
          >
            <path d="M2.992 16.342a2 2 0 0 1 .094 1.167l-1.065 3.29a1 1 0 0 0 1.236 1.168l3.413-.998a2 2 0 0 1 1.099.092 10 10 0 1 0-4.777-4.719" />
          </svg>
        </ToolbarButton>
        <ToolbarSeparator />
        <ToolbarLink href="#files" onClick={follow}>
          <svg
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="2"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
          >
            <path d="M6 22a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h8a2.4 2.4 0 0 1 1.704.706l3.588 3.588A2.4 2.4 0 0 1 20 8v12a2 2 0 0 1-2 2z" />
            <path d="M14 2v5a1 1 0 0 0 1 1h5" />
          </svg>
          Files changed
        </ToolbarLink>
        <ToolbarLink aria-label="Checks" href="#checks" onClick={follow}>
          <svg
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            stroke-width="2"
            stroke-linecap="round"
            stroke-linejoin="round"
            aria-hidden="true"
          >
            <path d="M15 3h6v6" />
            <path d="M10 14 21 3" />
            <path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6" />
          </svg>
        </ToolbarLink>
      </Toolbar>
      <p data-slot="hint">Showing: {page()}</p>
    </div>
  )
}

export { Example }
