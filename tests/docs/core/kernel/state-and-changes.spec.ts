test("history: undo and redo step through every change, from buttons and keys", async ({ page }) => {
  await openExamples(page, url)
  const first = page.getByRole("button", { name: "Row 1, column 1" })
  const second = page.getByRole("button", { name: "Row 2, column 2" })
  const example = page.locator("[data-example]").filter({ has: first })
  const undo = example.getByRole("button", { name: "Undo" })
  const redo = example.getByRole("button", { name: "Redo" })
  await first.scrollIntoViewIfNeeded()
  await expect(undo).toBeDisabled()
  await first.click()
  await second.click()
  await expect(second).toHaveAttribute("aria-pressed", "true")
  await undo.click()
  await expect(second).toHaveAttribute("aria-pressed", "false")
  await expect(first).toHaveAttribute("aria-pressed", "true")
  await redo.click()
  await expect(second).toHaveAttribute("aria-pressed", "true")
  await expect(redo).toBeDisabled()
  await first.focus()
  await page.keyboard.press("ControlOrMeta+z")
  await page.keyboard.press("ControlOrMeta+z")
  await expect(first).toHaveAttribute("aria-pressed", "false")
  await expect(undo).toBeDisabled()
  await page.keyboard.press("ControlOrMeta+Shift+z")
  await expect(first).toHaveAttribute("aria-pressed", "true")
})

