test("undo for typing: a run of keys is one step, and map and reset change every step", async ({ page }) => {
  await page.clock.install()
  await openExamples(page, url)
  const notes = page.getByRole("textbox", { name: "Notes" })
  const example = page.locator("[data-example]").filter({ has: notes })
  const undo = example.getByRole("button", { name: "Undo" })
  await notes.pressSequentially("teh cat")
  await page.clock.runFor(1000)
  await notes.pressSequentially(" sat")
  await undo.click()
  await expect(notes).toHaveValue("teh cat")
  await example.getByRole("button", { name: "Redo" }).click()
  await expect(notes).toHaveValue("teh cat sat")
  await example.getByRole("button", { name: "Fix “teh”" }).click()
  await expect(notes).toHaveValue("the cat sat")
  await undo.click()
  await expect(notes).toHaveValue("the cat")
  await example.getByRole("button", { name: "Clear" }).click()
  await expect(notes).toHaveValue("")
  await expect(undo).toBeDisabled()
})

