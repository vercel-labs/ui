// @vitest-environment node
import { expect, test } from "vitest"
import manifest from "../package.json"

const functions = /^create\w*Controller$|^createToaster$|^createAgent$/
const isComponent = (value: unknown) =>
  typeof value === "object" && value !== null && ("setup" in value || "render" in value)

// The Nuxt module reads this list instead of importing every entry at startup.
// After adding an entry or a part, update it with `pnpm test -u nuxt-names`.
test("the Nuxt module's names match the entries' exports", async () => {
  const seen = new Set<string>()
  const lines: string[] = []
  for (const path of Object.keys(manifest.exports)) {
    if (path === "." || path === "./nuxt") continue
    const values: Record<string, unknown> = await import(`../src/${path.slice(2)}.ts`)
    const parts: string[] = []
    const calls: string[] = []
    for (const [name, value] of Object.entries(values).sort(([a], [b]) => a.localeCompare(b))) {
      if (seen.has(name)) continue
      if (isComponent(value)) parts.push(name)
      else if (functions.test(name)) calls.push(name)
      else continue
      seen.add(name)
    }
    if (parts.length || calls.length)
      lines.push(`  "${path.slice(2)}": [${JSON.stringify(parts)}, ${JSON.stringify(calls)}],`)
  }
  const source = `// Generated by test/nuxt-names.test.ts: each entry's parts, then its functions.\nconst names: Record<string, [string[], string[]]> = {\n${lines.join("\n")}\n}\n\nexport { names }\n`
  await expect(source).toMatchFileSnapshot("../src/nuxt-names.ts")
})
